import { describe, it } from 'vitest'
import { renderMarkdown } from './markdown-renderer'

// 临时探针：复现「整篇加粗」问题——用 MySQL 里那条消息的真实原文跑渲染器
const RAW = `嗨呀！问到点子上了——我这套 AI 口播流水线，跑起来是六个工位接力，一个都不许摸鱼👇
**1. 选题侦察**
先不提笔。我会去热搜里捞一把（微博/抖音/小红书全扫），再用选题评估过一遍「这个话题有没有人点、有没有人吵」。侦察兵阵亡的话，后面全白搭。
**2. 钩子先定生死**
口播最怕前3秒劝退。我会一次性甩出5-8个开头变体——悬念型、数字型、反常识型都摆桌上，选那个让人「咦？」一下的。这一步不过关，正文写得再美也是废稿。
**3. 正文搭骨架**
按你的账号调性走：是要干货清单、故事体还是犀利吐槽。口播跟图文不一样——句子必须短、必须有节奏、必须能念出来不咬舌头。写的时候我脑子里是配着呼吸感和停顿念的。
**4. 去AI味急救**
这步我最来劲。填充词、公式化连接词、那股「综上所述」的塑料味，全砍。改写成人真的会说的话。老实说，十篇稿子八篇死在这关。
**5. 合规·质量双关卡**
敏感词、绝对化用语、平台雷区过一遍，尤其讲科技产品的时候，「最强」「第一」这种词一冒头就得摁住。
**6. 落地·包装双关卡**
封面、标题、标签一梳理成套——封面文案、最后发布清单——预览、定稿，一样都不让你抢`

describe('bold probe', () => {
  it('renders raw content', () => {
    const html = renderMarkdown(RAW)
    // 输出完整 HTML 供人工检查 strong 落点
    console.log('=== RENDERED HTML ===')
    console.log(html)
    console.log('=== strong count ===', (html.match(/<strong>/g) || []).length)
  })
})
